// Criando a classe coms seus atributos e metodos - CARRO

package POO_DRI_;

public class Carro {
    private String marca;
    private String modelo;
    private int ano;
    // -> Métodos = Construtor

    public Carro (String marca, String modelo, int ano) {
        this.marca = marca;
        this.modelo = modelo;
        this.ano = ano;
    }

}